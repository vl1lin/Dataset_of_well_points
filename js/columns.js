/** Колонки, о которых уже предупредили в консоли (чтобы не повторять). */
const warned = new Set();

/**
 * Возвращает русский заголовок колонки.
 * Если перевода нет, возвращает исходное имя и один раз пишет предупреждение в консоль.
 * @param {string} column имя колонки как в CSV
 * @param {boolean} [warn] писать ли предупреждение о колонке без перевода
 *   (false — для результатов SQL, где колонки часто называются псевдонимами вроде «n»)
 * @returns {string} заголовок для таблицы
 */
export function getColumnTitle(column, warn = true) {
  const title = /** @type {Record<string, string>} */ (COLUMN_TITLES)[column];
  if (title !== undefined) return title;
  if (warn && !warned.has(column)) {
    warned.add(column);
    console.warn(`Нет русского названия для колонки «${column}»`);
  }
  return column;
}
